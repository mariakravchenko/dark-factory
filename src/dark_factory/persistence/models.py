"""SQLAlchemy 2.0 typed ORM models for the durable run substrate (Plan 01-04).

Three tables are defined here and nothing else: ``runs`` (STATE-02), ``role_executions``
(STATE-03) and ``run_events`` (STATE-06 / D-22). They are plain SQLAlchemy classes,
deliberately **separate** from the frozen pydantic v2 boundary models in
``dark_factory.domain`` — SQLModel is not used and no ORM class inherits from a
pydantic model (project guidelines, "What NOT to Use").

Schema-shaping decisions carried by migration ``0001`` (Task 1 checkpoint —
``recommended`` = A1 + B1 + C1):

* **A1 — UUID v4 primary keys.** ``runs.id`` and the matching foreign keys on
  ``role_executions`` and ``run_events`` are ``uuid`` columns with a client-side
  ``uuid4`` default. A run id is safe to print on stdout line 1 and paste into
  ``resume`` without leaking a row count or colliding across machines once Phase 11
  has two machines writing.
* **B1 — ``sa.Enum(RunStatus, native_enum=False)``.** ``runs.status`` is a
  ``VARCHAR`` + ``CHECK`` constraint carrying **all ten** STATE-07 values from the
  first revision, not a native PostgreSQL ``ENUM`` type — a future value change is
  an ordinary ``ALTER TABLE`` constraint edit, never ``ALTER TYPE ... ADD VALUE``.
* **C1 — ``run_events.seq`` is a ``BigInteger`` identity column** (``GENERATED BY
  DEFAULT AS IDENTITY``). Event ordering is **always** ``ORDER BY seq`` and never
  ``ORDER BY created_at`` — timestamps skew across machines once Phase 11
  introduces cross-machine resume. See ``RunEvent`` below.

**Timestamps come from the database clock.** Every ``created_at`` / ``updated_at``
uses ``server_default=func.now()`` (and ``onupdate=func.now()``); no module writes
``datetime.now()`` / ``datetime.utcnow()`` into a persisted column, so Phase 11's
two machines cannot disagree about ordering.

**Retry counters are columns, never derived (D-19).** ``role_executions.attempt``
and ``runs.qa_developer_iterations`` / ``runs.quality_gate_iterations`` are NOT
NULL integers; they are incremented only in the one mutation path, never by
counting rows or folding events.

**Artifact durability (D-21).** ``artifacts`` (Phase 4, migration ``0004``)
stores :class:`ArtifactReference` **metadata only** — ``id, run_id,
role_execution_id, type, path, checksum, metadata, created_at`` — and never
artifact content. Artifact content lives on the filesystem under a per-run
directory (``.dark-factory/runs/<run-id>/``) and, in Phase 5, travels between
machines by being committed to a ``.dark-factory/`` path on the run's working
branch that is excluded from the published diff. No column on
:class:`ArtifactReference` holds artifact content.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

import sqlalchemy as sa
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from dark_factory.domain.interaction import InteractionStatus
from dark_factory.domain.status import RunStatus

__all__ = [
    "ArtifactReference",
    "Base",
    "HumanInteraction",
    "RoleExecution",
    "Run",
    "RunEvent",
]

# VARCHAR + CHECK carrying every STATE-07 value from revision 0001 (B1). Shared
# between the three places that must agree: this column, the CHECK constraint, and
# migration 0001.
_RUN_STATUS = sa.Enum(
    RunStatus,
    native_enum=False,
    create_constraint=True,
    length=32,
    name="run_status",
    values_callable=lambda enum: [member.value for member in enum],
)

# Exact structural mirror of ``_RUN_STATUS`` for ``human_interactions.status``
# (STATE-04). ``native_enum=False`` is the load-bearing part: it produces a
# ``VARCHAR`` + a named ``CHECK`` (``interaction_status``), so a future value edit
# is an ordinary ``ALTER TABLE ... CHECK`` constraint change, never
# ``ALTER TYPE ... ADD VALUE``. Shared by this column, the CHECK constraint and
# migration 0003.
_INTERACTION_STATUS = sa.Enum(
    InteractionStatus,
    native_enum=False,
    create_constraint=True,
    length=16,
    name="interaction_status",
    values_callable=lambda enum: [member.value for member in enum],
)


class Base(DeclarativeBase):
    """Declarative base for every Dark Factory ORM model."""


class Run(Base):
    """One durable delivery run — the STATE-02 column set (STATE-08: fully
    reconstructable from these columns alone)."""

    __tablename__ = "runs"

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    source_kind: Mapped[str] = mapped_column(sa.String(32), nullable=False)
    source_ref: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    normalized_task: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    workflow: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    status: Mapped[RunStatus] = mapped_column(_RUN_STATUS, nullable=False)
    # current_role is the authoritative pointer (RESEARCH A5); current_step is a
    # secondary ordinal stored alongside it, never the pointer of record.
    current_role: Mapped[str | None] = mapped_column(sa.String(64), nullable=True)
    current_step: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    repository: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    # base_branch / working_branch: present from 0001, unused until Phase 5 (D-20).
    base_branch: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    working_branch: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    # owner_token / lock_expires_at: the single-owner lease (0003), declared now,
    # exercised from plan 02-03 onward. NULL in both is exactly "unclaimed and
    # claimable", so no back-fill of existing rows is needed.
    # lock_expires_at is ONLY ever assigned from a SQL expression over the server
    # clock (``func.now() + <interval>``); the value in the column and every
    # comparison against it (``lock_expires_at < func.now()``) therefore live in
    # one clock domain — the database's. No process clock ever writes this column.
    owner_token: Mapped[uuid.UUID | None] = mapped_column(sa.Uuid(), nullable=True)
    lock_expires_at: Mapped[datetime | None] = mapped_column(
        sa.DateTime(timezone=True), nullable=True
    )
    pr_number: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    pr_url: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    # published_commit_sha (Phase 10, GIT-03/GIT-04, migration 0006, D-06): the
    # SHA of the commit the publish step pushed immediately before opening the
    # pull request, or NULL when the run has not yet published. Deliberately
    # distinct from ``RoleExecution.wip_commit_sha`` above -- that column is
    # WIP-recovery-specific and must never be repurposed as the publish SHA,
    # and this column is never read or written by the WIP-recovery path.
    # Written at most once per run, by ``apply_transition``'s ``publish_fields``
    # patch (the one mutation path).
    published_commit_sha: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    qa_developer_iterations: Mapped[int] = mapped_column(
        sa.Integer, nullable=False, server_default=sa.text("0")
    )
    quality_gate_iterations: Mapped[int] = mapped_column(
        sa.Integer, nullable=False, server_default=sa.text("0")
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        nullable=False,
        server_default=sa.func.now(),
        onupdate=sa.func.now(),
    )


class RoleExecution(Base):
    """One row per role attempt — the STATE-03 column set. A retry is a **new
    row**, never an update of an existing one; ``attempt`` starts at 1.

    ``attempt`` is computed as ``MAX(attempt) + 1`` scoped to ``(run_id, role)``
    under a ``runs``-row lock in the one mutation path, so duplicates cannot
    occur there. ``uq_role_exec_attempt`` is defence-in-depth: a future writer
    that forgets the lock hits a constraint violation, not a silent duplicate
    (added in migration ``0002``)."""

    __tablename__ = "role_executions"
    __table_args__ = (
        sa.UniqueConstraint("run_id", "role", "attempt", name="uq_role_exec_attempt"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("runs.id"), nullable=False, index=True
    )
    role: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    worker: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    status: Mapped[str] = mapped_column(sa.String(32), nullable=False)
    attempt: Mapped[int] = mapped_column(sa.Integer, nullable=False)
    worker_session_id: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    result: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    error: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    # wip_commit_sha (Phase 5, GIT-01/GIT-02, migration 0005): the SHA of the
    # recovery commit this attempt made while entering, or NULL. NULL means
    # exactly what NULL means on the lease columns above -- "this attempt
    # performed no recovery" -- a git fact recorded per attempt, never derived
    # from git state at read time. Set once, at most, per attempt, by a
    # ``patch``-mode write (see ``RoleExecutionWrite.mode`` in mutations.py)
    # before the attempt's own worker call; never cleared by that attempt's
    # later completion write.
    wip_commit_sha: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        nullable=False,
        server_default=sa.func.now(),
        onupdate=sa.func.now(),
    )


class RunEvent(Base):
    """Append-only audit trail (D-22). ``run_events`` is **never** folded to
    compute a run's position — that is read from ``runs`` + the latest
    ``role_executions`` row (STATE-06). Ordering is defined by ``seq``, a
    database-generated monotonic identity column, and **never** by ``created_at``:
    once Phase 11 has two machines writing, wall-clock timestamps skew but ``seq``
    stays monotonic. The composite ``(run_id, seq)`` index serves the only query
    shape this table has — "this run's events in order"."""

    __tablename__ = "run_events"
    __table_args__ = (sa.Index("ix_run_events_run_id_seq", "run_id", "seq"),)

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    seq: Mapped[int] = mapped_column(
        sa.BigInteger, sa.Identity(always=False), nullable=False
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("runs.id"), nullable=False
    )
    role_execution_id: Mapped[uuid.UUID | None] = mapped_column(
        sa.Uuid(), sa.ForeignKey("role_executions.id"), nullable=True
    )
    type: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )


class HumanInteraction(Base):
    """One row per question asked of a human (STATE-04). ``status`` is a
    ``VARCHAR`` + CHECK carrying exactly ``WAITING`` / ``ANSWERED`` / ``CANCELLED``
    (never a native PG ``ENUM``), so a future value edit is a constraint change.

    ``uq_one_waiting_interaction_per_run`` is a **partial** unique index on
    ``run_id`` restricted to ``status = 'WAITING'``. It is what turns "find the
    pending question for this run" into a single-row lookup, and it turns a
    duplicate pause into a constraint violation rather than a silent second open
    row — the same defence-in-depth philosophy as ``uq_role_exec_attempt`` on
    ``role_executions``. Because it is partial, any number of ``ANSWERED`` /
    ``CANCELLED`` rows may coexist for one run.

    ``role_execution_id`` is NOT NULL: every question in the roadmap originates in
    a role attempt, so the "which attempt asked this?" join is total, not
    optional. ``question`` is a single ``TEXT`` column holding the newline-join of
    ``WorkerResult.questions`` (already a ``list[str]``), redacted before write in
    the one mutation path.
    """

    __tablename__ = "human_interactions"
    __table_args__ = (
        sa.Index(
            "uq_one_waiting_interaction_per_run",
            "run_id",
            unique=True,
            postgresql_where=sa.text("status = 'WAITING'"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("runs.id"), nullable=False, index=True
    )
    role_execution_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("role_executions.id"), nullable=False
    )
    question: Mapped[str] = mapped_column(sa.Text, nullable=False)
    answer: Mapped[str | None] = mapped_column(sa.Text, nullable=True)
    # clarification_comment_id / github_comment_id (Phase 10, GIT-04/GIT-05,
    # migration 0006, D-05): the GitHub comment ids this interaction ties to --
    # the id of the clarification comment Dark Factory itself posted when it
    # asked (``ask`` mode, plan 10-03), and the id of the inbound comment that
    # answered it (``answer`` mode, plan 10-04). Both ``sa.BigInteger``, not
    # ``sa.Integer``: GitHub comment ids already exceed the 32-bit range, and
    # ``sa.Integer`` would silently overflow/truncate one. Both nullable, no
    # server default, no backfill -- the same posture as every other Phase 10
    # column added in this migration.
    clarification_comment_id: Mapped[int | None] = mapped_column(
        sa.BigInteger, nullable=True
    )
    github_comment_id: Mapped[int | None] = mapped_column(sa.BigInteger, nullable=True)
    status: Mapped[InteractionStatus] = mapped_column(
        _INTERACTION_STATUS, nullable=False
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    answered_at: Mapped[datetime | None] = mapped_column(
        sa.DateTime(timezone=True), nullable=True
    )


class ArtifactReference(Base):
    """One row per artifact file a role attempt produced (ART-01/02/03). Neon
    holds **metadata only** -- ``id, run_id, role_execution_id, type, path,
    checksum, metadata, created_at`` -- never the file's body text; the
    filesystem under ``.dark-factory/runs/<run-id>/`` holds the real content.

    ``uq_artifact_role_execution_path`` is the same defence-in-depth philosophy
    as ``uq_role_exec_attempt`` / ``uq_one_waiting_interaction_per_run``: two
    artifacts reported for the same attempt at the same path collide rather
    than silently merge.

    The Python attribute is ``artifact_metadata`` -- ``metadata`` is reserved on
    a SQLAlchemy declarative class (``Base.metadata``) -- but the database
    column name stays ``metadata`` exactly as this module's docstring (lines
    36-45) already promised.
    """

    __tablename__ = "artifacts"
    __table_args__ = (
        sa.UniqueConstraint(
            "role_execution_id", "path", name="uq_artifact_role_execution_path"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("runs.id"), nullable=False, index=True
    )
    role_execution_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("role_executions.id"), nullable=False
    )
    type: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    path: Mapped[str] = mapped_column(sa.String, nullable=False)
    checksum: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    artifact_metadata: Mapped[dict[str, Any]] = mapped_column(
        "metadata", JSONB, nullable=False, server_default=sa.text("'{}'::jsonb")
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )

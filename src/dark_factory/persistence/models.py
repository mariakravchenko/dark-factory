"""SQLAlchemy 2.0 typed ORM models for the durable run substrate (Plan 01-04).

Three tables are defined here and nothing else: ``runs`` (STATE-02), ``role_executions``
(STATE-03) and ``run_events`` (STATE-06 / D-22). They are plain SQLAlchemy classes,
deliberately **separate** from the frozen pydantic v2 boundary models in
``dark_factory.domain`` — SQLModel is not used and no ORM class inherits from a
pydantic model (project guidelines, "What NOT to Use").

Schema-shaping decisions carried by migration ``0001`` (Task 1 checkpoint —
``recommended`` = A1 + B1 + C1):

* **A1 — UUID v4 primary keys.** ``runs.id`` and the matching foreign keys on
  ``role_executions`` and ``run_events`` are ``uuid`` columns with a client-side
  ``uuid4`` default. A run id is safe to print on stdout line 1 and paste into
  ``resume`` without leaking a row count or colliding across machines once Phase 11
  has two machines writing.
* **B1 — ``sa.Enum(RunStatus, native_enum=False)``.** ``runs.status`` is a
  ``VARCHAR`` + ``CHECK`` constraint carrying **all ten** STATE-07 values from the
  first revision, not a native PostgreSQL ``ENUM`` type — a future value change is
  an ordinary ``ALTER TABLE`` constraint edit, never ``ALTER TYPE ... ADD VALUE``.
* **C1 — ``run_events.seq`` is a ``BigInteger`` identity column** (``GENERATED BY
  DEFAULT AS IDENTITY``). Event ordering is **always** ``ORDER BY seq`` and never
  ``ORDER BY created_at`` — timestamps skew across machines once Phase 11
  introduces cross-machine resume. See ``RunEvent`` below.

**Timestamps come from the database clock.** Every ``created_at`` / ``updated_at``
uses ``server_default=func.now()`` (and ``onupdate=func.now()``); no module writes
``datetime.now()`` / ``datetime.utcnow()`` into a persisted column, so Phase 11's
two machines cannot disagree about ordering.

**Retry counters are columns, never derived (D-19).** ``role_executions.attempt``
and ``runs.qa_developer_iterations`` / ``runs.quality_gate_iterations`` are NOT
NULL integers; they are incremented only in the one mutation path, never by
counting rows or folding events.

**Artifact durability, recorded for schema shape only (D-21).** Phase 1 creates
no ``artifacts`` table. The future ``artifacts`` table (Phase 4) will store
``ArtifactReference`` **metadata only** — ``id, run_id, role_execution_id, type,
path, checksum, metadata, created_at`` — and never artifact content. Artifact
content lives on the filesystem under a per-run directory
(``.dark-factory/runs/<run-id>/``) and, in Phase 5, travels between machines by
being committed to a ``.dark-factory/`` path on the run's working branch that is
excluded from the published diff. This is written down because it shapes the
schema, not because it is built now: no model here defines a column intended to
hold artifact content.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

import sqlalchemy as sa
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from dark_factory.domain.status import RunStatus

__all__ = ["Base", "RoleExecution", "Run", "RunEvent"]

# VARCHAR + CHECK carrying every STATE-07 value from revision 0001 (B1). Shared
# between the three places that must agree: this column, the CHECK constraint, and
# migration 0001.
_RUN_STATUS = sa.Enum(
    RunStatus,
    native_enum=False,
    create_constraint=True,
    length=32,
    name="run_status",
    values_callable=lambda enum: [member.value for member in enum],
)


class Base(DeclarativeBase):
    """Declarative base for every Dark Factory ORM model."""


class Run(Base):
    """One durable delivery run — the STATE-02 column set (STATE-08: fully
    reconstructable from these columns alone)."""

    __tablename__ = "runs"

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    source_kind: Mapped[str] = mapped_column(sa.String(32), nullable=False)
    source_ref: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    normalized_task: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    workflow: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    status: Mapped[RunStatus] = mapped_column(_RUN_STATUS, nullable=False)
    # current_role is the authoritative pointer (RESEARCH A5); current_step is a
    # secondary ordinal stored alongside it, never the pointer of record.
    current_role: Mapped[str | None] = mapped_column(sa.String(64), nullable=True)
    current_step: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    repository: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    # base_branch / working_branch: present from 0001, unused until Phase 5 (D-20).
    base_branch: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    working_branch: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    pr_number: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    pr_url: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    qa_developer_iterations: Mapped[int] = mapped_column(
        sa.Integer, nullable=False, server_default=sa.text("0")
    )
    quality_gate_iterations: Mapped[int] = mapped_column(
        sa.Integer, nullable=False, server_default=sa.text("0")
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        nullable=False,
        server_default=sa.func.now(),
        onupdate=sa.func.now(),
    )


class RoleExecution(Base):
    """One row per role attempt — the STATE-03 column set. A retry is a **new
    row**, never an update of an existing one; ``attempt`` starts at 1."""

    __tablename__ = "role_executions"

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("runs.id"), nullable=False, index=True
    )
    role: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    worker: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    status: Mapped[str] = mapped_column(sa.String(32), nullable=False)
    attempt: Mapped[int] = mapped_column(sa.Integer, nullable=False)
    worker_session_id: Mapped[str | None] = mapped_column(sa.String, nullable=True)
    result: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    error: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        nullable=False,
        server_default=sa.func.now(),
        onupdate=sa.func.now(),
    )


class RunEvent(Base):
    """Append-only audit trail (D-22). ``run_events`` is **never** folded to
    compute a run's position — that is read from ``runs`` + the latest
    ``role_executions`` row (STATE-06). Ordering is defined by ``seq``, a
    database-generated monotonic identity column, and **never** by ``created_at``:
    once Phase 11 has two machines writing, wall-clock timestamps skew but ``seq``
    stays monotonic. The composite ``(run_id, seq)`` index serves the only query
    shape this table has — "this run's events in order"."""

    __tablename__ = "run_events"
    __table_args__ = (sa.Index("ix_run_events_run_id_seq", "run_id", "seq"),)

    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), primary_key=True, default=uuid.uuid4
    )
    seq: Mapped[int] = mapped_column(
        sa.BigInteger, sa.Identity(always=False), nullable=False
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(), sa.ForeignKey("runs.id"), nullable=False
    )
    role_execution_id: Mapped[uuid.UUID | None] = mapped_column(
        sa.Uuid(), sa.ForeignKey("role_executions.id"), nullable=True
    )
    type: Mapped[str] = mapped_column(sa.String(64), nullable=False)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
